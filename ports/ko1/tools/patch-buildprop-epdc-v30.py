#!/usr/bin/env python3
"""KO1 v30: also enable the A2 waveform and shorten the settle wait.

What v29 established
--------------------
With both properties in build.prop's *text* area the device finally reads them:

    $ getprop debug.pw3.epdc.fast
    1
    $ getprop debug.pw3.epdc.full_every
    20

preinit rewrites build.prop and drops the 58-byte NUL padding at its tail, so
anything parked there is lost -- that is why v27's `fast` and both of v28's
properties vanished.

But `a2` stayed at 0.  The properties the vendor blob actually carries are
eleven, not three:

    debug.pw3.epdc.a2             <- the A2 waveform itself
    debug.pw3.epdc.fast
    debug.pw3.epdc.full_every
    debug.pw3.epdc.settle_ms
    debug.pw3.epdc.clean
    debug.pw3.epdc.contrast
    debug.pw3.epdc.dither
    debug.pw3.epdc.exact
    debug.pw3.epdc.direct_percent
    debug.pw3.epdc.move_percent
    debug.pw3.epdc.page_percent

`fast` is therefore not the A2 switch -- it enables some other fast path and
left the waveform choice on GL16.  `settle_ms` is separate again: the open log
line reports it, and it defaults to 350 ms of fixed wait per update:

    PW3Gralloc: EPDC framebuffer open ready: ... settle_ms=350

Both are only read at SurfaceFlinger startup, so a power cycle is not enough
(verified: setprop + screen off/on produced no new open log).  They go in the
image.

Byte budget
-----------
Two more equal-length substitutions, both on boilerplate lines that buildinfo
generated and that carry no information:

    line 3   "# autogenerated by buildinfo.sh"          31 B ->
             "debug.pw3.epdc.settle_ms=150" + padding
    line 84  "# ADDITIONAL_BUILD_PROPERTIES"            29 B ->
             "debug.pw3.epdc.a2=1" + padding

Padding is spaces, so each replacement is exactly as long as the line it
replaces and the file, its text length and its tail padding all stay put.

Usage
-----
    patch-buildprop-epdc-v30.py --check
    patch-buildprop-epdc-v30.py                 # -> build/images/system-v30.img
    patch-buildprop-epdc-v30.py --verify PATH
"""
from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

SRC = pathlib.Path("build/images/system-v29.img")
DST = pathlib.Path("build/images/system-v30.img")

BLOCK = 83430
BLOCK_SIZE = 4096
INBLOCK = 58
FILE_SIZE = 4719
OFF = BLOCK * BLOCK_SIZE + INBLOCK

# (old line, new property text).  Padding with spaces makes lengths match.
SUBS = [
    (b"# autogenerated by vendor_buildinfo.sh", b"debug.pw3.epdc.settle_ms=150"),
    (b"# ADDITIONAL_BUILD_PROPERTIES", b"debug.pw3.epdc.a2=1"),
]

WANT = [b"debug.pw3.epdc.fast=1", b"debug.pw3.epdc.full_every=20",
        b"debug.pw3.epdc.a2=1", b"debug.pw3.epdc.settle_ms=150"]


def blob_at(img: pathlib.Path) -> bytes:
    with img.open("rb") as f:
        f.seek(OFF)
        return f.read(FILE_SIZE)


def text_len(blob: bytes) -> int:
    end = len(blob)
    while end > 0 and blob[end - 1] == 0:
        end -= 1
    return end


def verify(blob: bytes, tag: str = "result") -> bool:
    t = text_len(blob)
    body = blob[:t]
    ok = len(blob) == FILE_SIZE
    print(f"{tag}: file={len(blob)} text={t} padding={len(blob) - t}")
    for w in WANT:
        hit = w in body
        ok = ok and hit
        print(f"  {w.decode():32s} {'yes' if hit else 'NO'}")
    # each property line must be terminated by a newline
    for w in WANT:
        i = body.find(w)
        if i >= 0:
            j = body.find(b"\n", i)
            gap = body[i + len(w):j] if j >= 0 else b"<none>"
            clean = gap.strip() == b""
            ok = ok and clean
            print(f"  {w.decode():32s} line ends ok: {'yes' if clean else 'NO'}")
    return ok


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--verify", metavar="PATH")
    ap.add_argument("--src", default=str(SRC))
    ap.add_argument("--dst", default=str(DST))
    args = ap.parse_args()

    if args.verify:
        blob = blob_at(pathlib.Path(args.verify))
        ok = verify(blob, "verify")
        print("RESULT:", "PASS" if ok else "FAIL")
        return 0 if ok else 1

    src = pathlib.Path(args.src)
    if not src.exists():
        print(f"no v29 image at {src} -- run patch-buildprop-epdc-v29.py first")
        return 1

    blob = blob_at(src)
    if len(blob) != FILE_SIZE:
        print(f"unexpected build.prop size {len(blob)}")
        return 1
    if b"debug.pw3.epdc.a2=" in blob:
        print("image already carries the a2 property")
        return 1

    new = blob
    for old, prop in SUBS:
        if old not in new:
            print(f"anchor missing: {old!r}")
            return 1
        if len(prop) > len(old):
            print(f"property longer than anchor: {len(prop)} > {len(old)}")
            return 1
        new = new.replace(old, prop + b" " * (len(old) - len(prop)), 1)

    if len(new) != FILE_SIZE:
        print(f"length changed: {len(new)} != {FILE_SIZE}")
        return 1

    if args.check:
        print("anchors ok, size stays", len(new), "text", text_len(new))
        for old, prop in SUBS:
            print(f"  {old.decode():35s} -> {prop.decode()}")
        return 0

    print("copying image ...")
    dst = pathlib.Path(args.dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    with src.open("rb") as fi, dst.open("wb") as fo:
        while True:
            chunk = fi.read(1 << 22)
            if not chunk:
                break
            fo.write(chunk)

    with dst.open("r+b") as f:
        f.seek(OFF)
        f.write(new)

    before = hashlib.sha256(src.read_bytes()).hexdigest()
    after = hashlib.sha256(dst.read_bytes()).hexdigest()
    print("sha256:", before[:16], "->", after[:16])

    ok = verify(blob_at(dst))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
